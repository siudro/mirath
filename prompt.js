/* تجميع النص الكامل الذي يُرسل للنموذج.
   knowledgebase.js يُحقن كقاعدة بيانات حرفية — لا حاجة للنموذج أن «يتذكرها». */
function composeFullPrompt({ kb }) {
  const kbSection = kb
    ? "\n\n# —— قاعدة المعرفة المرافقة [إضافة] ——\n\n"
      + "هذه قاعدة بيانات حرفية. اقرأ منها لا من ذاكرتك. كل مادة لها حكم صريح ومصدر.\n\n"
      + "| المادة | الحكم | تنطبق على | المصدر | القيود |\n"
      + "|---|---|---|---|---|\n"
      + (kb.herbs || [])
        .map(
          (h) =>
            `| ${h.ar} | ${h.verdictLabel} | ${
              h.appliesTo.length ? h.appliesTo.join("، ") : "لا شيء — ممنوعة"
            } | ${h.source} | ${h.notes} |`
        )
        .join("\n")
      + "\n\n**المصادر الكاملة:**\n"
      + (kb.sources || []).map((s) => `- ${s.ar}${s.url ? ` — ${s.url}` : ""}`).join("\n")
    : "";

  return [
    SYSTEM_PROMPT,
    AGENT_RULES,
    FORMAT_RULES,
    kbSection,
  ]
    .filter(Boolean)
    .join("\n");
}

