def ar(t):
    return get_display(reshape(str(t or "")))


def clean(t):
    """يُزيل الوسوم قبل التشكيل: التشكيل يعكس ترتيب <b> فيفسد الاقتران."""
    t = str(t or "")
    t = t.replace("<i>", "«").replace("</i>", "»")
    t = re.sub(r"<b>(.+?)</b>", r"\1", t, flags=re.S)
    t = re.sub(r"</?b>", "", t)
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return t


def P(t, s="b"):
    return Paragraph(ar(clean(t)), ST[s])


def B(t):
    return Paragraph(ar("• " + clean(t)), ST["l"])


def NUM(t):
    return Paragraph(ar(clean(t)), ST["n"])


def table(rows, widths):
    data = [[Paragraph(ar(clean(c)), ST["cb"] if i == 0 else ST["c"]) for c in r]
            for i, r in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef3f7")),
        ("GRID", (0, 0), (-1, -1), 0.4, RULE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return t



def workflow_diagram(width=158 * mm, height=30 * mm):
    """مخطط مسار الوكيل — يُرسم بالعربية بعد التشكيل."""
    d = Drawing(width, height)
    boxes = [
        ("رسالة+صورة", "#e8f1f7"),
        ("فرز الخطورة", "#fdeaea"),
        ("قاعدة الأدلة", "#eef7ee"),
        ("الكاتب", "#eef2fa"),
        ("المدقّق", "#fdf6e3"),
        ("١٣ بوابة", "#fdeaea"),
        ("إسعاف+نصح+تحذير", "#eef7ee"),
    ]
    bw, bh, gap = 20 * mm, 13 * mm, 3.2 * mm
    total = len(boxes) * bw + (len(boxes) - 1) * gap
    x0 = (width - total) / 2
    y = height / 2 - bh / 2 + 1 * mm
    prev = None
    for i, (label, col) in enumerate(boxes):
        x = x0 + i * (bw + gap)
        d.add(Rect(x, y, bw, bh, fillColor=colors.HexColor(col),
                   strokeColor=colors.HexColor("#b8c8d4"), strokeWidth=0.7, rx=2, ry=2))
        d.add(String(x + bw / 2, y + bh / 2 - 2, ar(label), fontName="A", fontSize=6.2,
                     textAnchor="middle", fillColor=INK))
        if prev is not None:
            d.add(Line(prev, y + bh / 2, x, y + bh / 2,
                       strokeColor=colors.HexColor("#8fa9bb"), strokeWidth=1.0))
        prev = x + bw
    return d


